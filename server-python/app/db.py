@lru_cache(maxsize=2048)
def _translate(sql: str, returning: bool = True) -> str:
    """SQLite-flavoured SQL -> Postgres.

    Cached: the SQL strings in this codebase are literals, so the same handful of
    statements are translated over and over. Without the cache this ran several
    str.replace passes plus a regex on every single query.
    """
    s = sql
    s = s.replace("strftime('%Y-%m','now')", "to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM')")
    s = s.replace("datetime('now')", "to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')")
    s = s.replace("date('now')", "to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD')")

    head = s.lstrip()[:24].upper()
    if head.startswith("INSERT OR IGNORE"):
        i = s.upper().index("INSERT OR IGNORE")
        s = s[:i] + "INSERT" + s[i + len("INSERT OR IGNORE"):]
        if "ON CONFLICT" not in s.upper():
            s = s.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    elif returning and head.startswith("INSERT") and "RETURNING" not in s.upper():
        m = re.search(r"insert\s+into\s+\"?([a-zA-Z_]\w*)\"?", s, re.IGNORECASE)
        table = m.group(1).lower() if m else ""
        if table not in NO_ID_TABLES:
            s = s.rstrip().rstrip(";") + " RETURNING id"

    s = s.replace("?", "%s")
    return s


class _Row:

    __slots__ = ("_names", "_vals", "_index")

    def __init__(self, names, values):
        self._names = names
        self._vals = values
        self._index = None

    def __getitem__(self, key):
        if isinstance(key, str):
            if self._index is None:
                self._index = {n: i for i, n in enumerate(self._names)}
            return self._vals[self._index[key]]
        return self._vals[key]

    def __iter__(self):
        return iter(self._vals)

    def __len__(self):
        return len(self._vals)

    def keys(self):
        return list(self._names)

    def get(self, key, default=None):
        try:
            return self[key]
        except (KeyError, IndexError):
            return default


def _pg_row_factory(cursor):
    cols = cursor.description
    names = [c.name for c in cols] if cols else []

    def make_row(values):
        return _Row(names, values)

    return make_row


class _PgCursor:
    """Materialises the result and closes the underlying cursor immediately.

    The previous version held an open psycopg cursor for the caller to fetch from
    later. That was survivable when every connection was thrown away after one
    request, but with a pool the connections are long-lived and those cursors
    piled up on them until garbage collection. psycopg buffers the whole result
    for a client-side cursor anyway, so reading it out here costs no extra memory.
    """

    __slots__ = ("lastrowid", "rowcount", "_rows", "_pos")

    def __init__(self, cur, translated_sql):
        self.lastrowid = None
        self.rowcount = cur.rowcount
        self._rows = []
        self._pos = 0
        try:
            if translated_sql.lstrip()[:6].upper() == "INSERT" and "RETURNING" in translated_sql.upper():
                # Consume the RETURNING row into lastrowid and expose nothing,
                # matching the previous behaviour exactly.
                row = cur.fetchone()
                self.lastrowid = row[0] if row is not None else None
            elif cur.description is not None:
                self._rows = cur.fetchall()
        finally:
            cur.close()

    def fetchone(self):
        if self._pos >= len(self._rows):
            return None
        row = self._rows[self._pos]
        self._pos += 1
        return row

    def fetchall(self):
        rows = self._rows[self._pos:]
        self._pos = len(self._rows)
        return rows

    def fetchmany(self, size=None):
        if size is None:
            size = len(self._rows) - self._pos
        rows = self._rows[self._pos:self._pos + size]
        self._pos += len(rows)
        return rows


class _PgConnection:

    __slots__ = ("_conn", "_owned")

    def __init__(self, conn, owned: bool = True):
        self._conn = conn
        # Pooled connections are borrowed: close() must hand them back, not tear
        # down the socket.
        self._owned = owned

    def execute(self, sql, params=()):
        translated = _translate(sql)
        cur = self._conn.cursor()
        cur.execute(translated, params or None)
        return _PgCursor(cur, translated)

    def executemany(self, sql, seq_of_params):
        translated = _translate(sql, returning=False)
        rows = list(seq_of_params)
        cur = self._conn.cursor()
        if rows:
            cur.executemany(translated, rows)
        return _PgCursor(cur, translated)

    def transaction(self):
        """Group several statements so they commit or roll back together.

        Connections are opened with autocommit=True, which means every execute()
        is its own transaction. That is the right default for this app's
        single-statement handlers, but it silently makes multi-row writes
        non-atomic: a loop that raises halfway leaves the earlier rows
        committed. Any handler writing more than one row should wrap the writes:

            with db.transaction():
                db.executemany(...)
                db.executemany(...)

        psycopg emits BEGIN on entry and COMMIT (or ROLLBACK, on exception) on
        exit, and nests correctly via savepoints if one of these is already open.
        """
        return self._conn.transaction()

    def close(self):
        if self._owned:
            self._conn.close()


_pool = None
_pool_lock = threading.Lock()
_pool_unavailable = False

POOL_MIN = int(os.environ.get("DB_POOL_MIN", "2"))
POOL_MAX = int(os.environ.get("DB_POOL_MAX", "10"))


def _get_pool():
    """Lazily built connection pool, or None if psycopg_pool isn't installed.

    Without this every request paid a fresh TCP + TLS + SCRAM handshake to the
    database. Against a remote host that is several hundred milliseconds, and
    opening a single project screen fires about six independent endpoints — so
    the handshakes alone dominated page load.
    """
    global _pool, _pool_unavailable
    if _pool is not None or _pool_unavailable:
        return _pool
    with _pool_lock:
        if _pool is not None or _pool_unavailable:
            return _pool
        try:
            from psycopg_pool import ConnectionPool
        except ImportError:
            _pool_unavailable = True
            print(
                "psycopg_pool is not installed — falling back to one connection "
                "per request, which is slow. Fix with: pip install 'psycopg_pool>=3.2'"
            )
            return None
        _pool = ConnectionPool(
            _PG_URL,
            min_size=POOL_MIN,
            max_size=POOL_MAX,
            kwargs={"autocommit": True, "row_factory": _pg_row_factory},
            timeout=15,
            max_idle=300,
            open=True,
        )
        return _pool


def get_connection():
    """A dedicated, unpooled connection. Used by init_db and the CLI scripts."""
    conn = psycopg.connect(
        _PG_URL,
        autocommit=True,
        row_factory=_pg_row_factory,
        connect_timeout=10,
    )
    return _PgConnection(conn)


def get_db():
    pool = _get_pool()
    if pool is None:
        conn = get_connection()
        try:
            yield conn
        finally:
            conn.close()
        return
    with pool.connection() as raw:
        yield _PgConnection(raw, owned=False)


def close_pool() -> None:
    """Release pooled connections on shutdown."""
    global _pool
    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


def init_db() -> None:
    """Apply the schema and seed data. Skippable with SKIP_DB_INIT=1.

    The DDL used to be sent one statement at a time — around sixty separate
    round trips to the database before the process could serve its first
    request. Postgres accepts the whole script in a single call, so this is now
    one round trip. Set SKIP_DB_INIT=1 on workers that don't need to migrate
    (only one process in a deployment has to run this).
    """
    if os.environ.get("SKIP_DB_INIT", "").strip().lower() in {"1", "true", "yes", "on"}:
        print("SKIP_DB_INIT is set — skipping schema/seed.")
        return
    conn = get_connection()
    try:
        raw = conn._conn
        script = re.sub(r"--[^\n]*", "", _PG_SCHEMA).strip()
        try:
            # psycopg sends a multi-statement script in one round trip.
            raw.execute(script)
        except psycopg.Error:
            # Fall back to statement-at-a-time so one unsupported statement
            # can't take the whole schema down.
            for statement in script.split(";"):
                statement = statement.strip()
                if statement:
                    raw.execute(statement)

        for statement in _OPTIONAL_DDL:
            try:
                raw.execute(statement)
            except psycopg.Error as exc:
                print(f"Optional DDL skipped ({exc.__class__.__name__}): {statement[:60]}…")
                if "idx_keywords_project_term" in statement:
                    # Plain ASCII on purpose. A Windows console defaults to
                    # cp1252, which has no U+2192, so an arrow here raised
                    # UnicodeEncodeError *inside the handler* and killed the
                    # whole server over what is only a warning.
                    print(
                        "  -> this project has duplicate keyword terms. Merge them with:\n"
                        "      cd server-python && python -m scripts.dedupe_keywords\n"
                        "    (add --commit once the dry run looks right)"
                    )

        _seed(conn)
    finally:
        conn.close()


def _seed_locations(conn) -> None:
    (have,) = conn.execute("SELECT COUNT(*) FROM locations").fetchone()
    if have == 0:
        from .locations import seed_rows

        rows = seed_rows()
        conn.executemany(
            "INSERT INTO locations (location_code, name, full_name, kind,"
            " country_code, region_code, country_iso, location_type, alt,"
            " name_key, search_key)"
            " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            rows,
        )
        print(f"Seeded {len(rows)} locations (countries + verified metro cities)")

    _backfill_location_keys(conn)


def _backfill_location_keys(conn) -> None:
    # EXISTS short-circuits on the first hit; COUNT(*) scanned the whole
    # locations table (~100k rows, and name_key isn't indexed) on every boot.
    row = conn.execute(
        "SELECT 1 FROM locations WHERE name_key IS NULL LIMIT 1"
    ).fetchone()
    if not row:
        return
    (stale,) = conn.execute("SELECT COUNT(*) FROM locations WHERE name_key IS NULL").fetchone()
    conn.execute(
        "UPDATE locations SET"
        "  name_key = LOWER(name),"
        "  search_key = ' ' || LOWER(REPLACE(REPLACE(REPLACE(full_name, ',', ' '), '  ', ' '), '  ', ' '))"
        "               || ' ' || LOWER(alt) || ' '"
        " WHERE name_key IS NULL"
    )
    print(f"Back-filled search keys on {stale:,} locations")


def _backfill_project_locations(conn) -> None:
    # Guard first: this UPDATE carries three correlated subqueries against
    # locations and used to run unconditionally on every startup, even when
    # there was nothing to backfill.
    row = conn.execute(
        "SELECT 1 FROM projects WHERE location_code IS NOT NULL"
        " AND country_code IS NULL LIMIT 1"
    ).fetchone()
    if not row:
        return
    conn.execute(
        "UPDATE projects SET"
        "  country_code = (SELECT l.country_code FROM locations l"
        "                  WHERE l.location_code = projects.location_code),"
        "  city_code = (SELECT CASE WHEN l.kind = 'city' THEN l.location_code END"
        "               FROM locations l WHERE l.location_code = projects.location_code),"
        "  location_label = (SELECT l.full_name FROM locations l"
        "                    WHERE l.location_code = projects.location_code)"
        " WHERE location_code IS NOT NULL AND country_code IS NULL"
    )


