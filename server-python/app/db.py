#: Applied one statement at a time, each tolerant of failure.
#:
#: The location autocomplete's second pass matches `search_key LIKE '%token%'`.
#: A leading wildcard can't use a btree index, so that pass sequentially scanned
#: the whole locations table — around 100k rows after a full DataForSEO import —
#: on every keystroke. A trigram GIN index makes substring matching indexable.
#:
#: pg_trgm ships with Postgres and is available on Supabase, but creating an
#: extension needs privileges a managed database may withhold. If either
#: statement fails the app keeps working exactly as before, just without the
#: index, so these are kept out of the main schema script.
#:
#: The unique index on keywords is here for a different reason: a database that
#: already contains duplicate terms will reject it, and that must not stop the
#: app from booting. Run `python -m scripts.dedupe_keywords --commit` to merge
#: the duplicates, after which this statement succeeds on the next start. Until
#: then add_keyword's own pre-insert check is the only guard, which is racy but
#: no worse than the behaviour it replaces.
